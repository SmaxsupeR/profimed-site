// Виджет Яндекс.Карт вместо OpenStreetMap — картография выглядит живее
// (не голый mapnik), и стиль карты совпадает с кнопками «Маршрут»/«Такси»
// ниже, которые уже ведут на Яндекс.
//
// oid=…&ol=biz вместо своей точки (pt=…,pm2rdl, было раньше) — так карта
// подсвечивает саму организацию «ProfiMed» из Яндекс.Бизнеса (её
// собственная красная метка с карточкой: название, рейтинг, часы, адрес,
// ближайшее метро), а не рисует поверх неё ещё одну универсальную синюю
// точку. С своей точкой на скриншоте были видны сразу два маркера почти
// друг на друге — наша синяя и родная бизнес-метка Яндекса рядом с ней,
// что читалось как два разных места, а не одно. Проверено на 350×300,
// 700×420 и 1080×420 (мобильный/планшетный/десктопный масштаб нашего
// iframe, см. Map.jsx): при недостатке места карточка организации не
// показывается вовсе (остаётся только подсвеченная метка и дороги вокруг),
// при достатке — не шире компактного угла, обзор карты и ближайшие
// подъездные дороги в обоих случаях остаются полностью видны. ll=/z=
// по-прежнему нужны явно — без них виджет в режиме oid/ol=biz открывает
// вид на пол-планеты вместо квартала.
export const MAP_EMBED_URL =
  'https://yandex.ru/map-widget/v1/' +
  `?ll=${CLINIC_LON}%2C${CLINIC_LAT}&z=16&oid=${YANDEX_ORG_ID}&ol=biz`;

// Точка подачи машины — выверена по спутнику со стороны подъезда: и такси,
// и навигатор должны привозить туда, где реально можно остановиться.
// Предыдущий вариант (41.300355, 69.267009) уводил за дом.
//
// Используется в ROUTE_URL/ROUTE_GEO_URL/TAXI_URL ниже — НЕ для центра
// карты (тот берёт CLINIC_LAT/LON выше). Отличается от него на несколько
// метров и это намеренно, а не рассинхрон: карту правильно центрировать на
// самой клинике, а машину/навигатор направлять к фасаду, где реально можно
// выйти и зайти внутрь. Не объединяй эти две пары координат в одну —
// площадка у входа и корпус здания на спутниковом снимке разнесены
// заметно, и «упрощение» до одной точки для кого-то из двух сценариев
// снова уведёт не туда (то за дом, как было раньше, то на крышу вместо
// подъезда).
export const ARRIVAL_LAT = 41.300392;
export const ARRIVAL_LON = 69.267335;

// Маршрут на Android — через geo:, чтобы открылось то навигационное
// приложение, которым человек пользуется (Яндекс Навигатор, 2ГИС, Google
// Карты), а не навязанное нами.
export const ROUTE_GEO_URL =
  `geo:${ARRIVAL_LAT},${ARRIVAL_LON}?q=${ARRIVAL_LAT},${ARRIVAL_LON}(ProfiMed)`;

// Везде остальное (десктоп, iOS) — обычная ссылка: geo: там либо не
// поддерживается, либо просто ничего не делает.
//
// rtt — режим маршрута у Яндекса. Указываем его явно у обеих кнопок, чтобы
// они вели в разные места, а не отличались одним параметром: auto открывает
// автомобильный маршрут (оттуда можно переключиться на пешком/транспорт),
// taxi — сразу вкладку заказа такси. Пустой rtt отдал бы выбор режима на
// усмотрение Яндекса.
export const ROUTE_URL = `https://yandex.ru/maps/?rtext=~${ARRIVAL_LAT},${ARRIVAL_LON}&rtt=auto`;

export const TAXI_URL = `https://yandex.ru/maps/?rtext=~${ARRIVAL_LAT},${ARRIVAL_LON}&rtt=taxi`;
