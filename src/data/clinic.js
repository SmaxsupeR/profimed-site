// Рамка карты вокруг точки: примерно ±550м по долготе и ±280м по широте —
// видно и саму клинику, и соседние ориентиры, по которым её ищут.
const PAD_LON = 0.005;
const PAD_LAT = 0.0025;

export const MAP_EMBED_URL =
  'https://www.openstreetmap.org/export/embed.html' +
  `?bbox=${CLINIC_LON - PAD_LON}%2C${CLINIC_LAT - PAD_LAT}%2C${CLINIC_LON + PAD_LON}%2C${CLINIC_LAT + PAD_LAT}` +
  `&layer=mapnik&marker=${CLINIC_LAT}%2C${CLINIC_LON}`;

// Точка подачи машины — выверена по спутнику со стороны подъезда: и такси,
// и навигатор должны привозить туда, где реально можно остановиться.
// Предыдущий вариант (41.300355, 69.267009) уводил за дом.
//
// Отличается от метки на карте (CLINIC_LAT/LON выше) на несколько метров и
// это намеренно: метке правильно стоять на самой клинике, машине — у входа.
export const ARRIVAL_LAT = 41.300392;
export const ARRIVAL_LON = 69.267335;

// Маршрут на Android — через geo:, чтобы открылось то навигационное
// приложение, которым человек пользуется (Яндекс Навигатор, 2ГИС, Google
// Карты), а не навязанное нами.
export const ROUTE_GEO_URL =
  `geo:${ARRIVAL_LAT},${ARRIVAL_LON}?q=${ARRIVAL_LAT},${ARRIVAL_LON}(ProfiMed)`;

// Везде остальное (десктоп, iOS) — обычная ссылка: geo: там либо не
// поддерживается, либо просто ничего не делает.
//
// rtt — режим маршрута у Яндекса. Указываем его явно у обеих кнопок, чтобы
// они вели в разные места, а не отличались одним параметром: auto открывает
// автомобильный маршрут (оттуда можно переключиться на пешком/транспорт),
// taxi — сразу вкладку заказа такси. Пустой rtt отдал бы выбор режима на
// усмотрение Яндекса.
export const ROUTE_URL = `https://yandex.ru/maps/?rtext=~${ARRIVAL_LAT},${ARRIVAL_LON}&rtt=auto`;

export const TAXI_URL = `https://yandex.ru/maps/?rtext=~${ARRIVAL_LAT},${ARRIVAL_LON}&rtt=taxi`;
